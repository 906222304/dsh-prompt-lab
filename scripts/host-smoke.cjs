/** Isolated smoke check against an installed DSH, run with its Node/Electron runtime. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { createRequire } = require('node:module');

async function main() {
  const modules = process.argv[2] || process.env.DSH_HOST_MODULES;
  if (!modules || !path.isAbsolute(modules)) throw new Error('Pass the absolute DSH node_modules directory as the first argument');
  const fromHost = createRequire(path.join(modules, 'prompt-lab-smoke.cjs'));
  const { Context } = fromHost('@deepseek-ai/cordis');
  const { SystemPrompt } = fromHost('@deepseek-ai/dsh-system-prompt');
  const { WebServer } = fromHost('@deepseek-ai/dsh-host-webserver');
  const version = fromHost('@deepseek-ai/dsh-system-prompt/package.json').version;
  const pluginVersion = require('../package.json').version;
  const plugin = require('../lib/index.js');
  const state = require('../lib/state.js');
  const ui = require('../lib/ui.js');
  const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'prompt-lab-host-smoke-'));
  const previousHome = process.env.DSH_HOME;
  process.env.DSH_HOME = temporary;
  const ctx = new Context();
  let service, injection, web, api;
  try {
    service = ctx.plugin(SystemPrompt, {});
    await new Promise(setImmediate);
    ctx.systemPrompt.context({ name: 'smoke:cwd', order: 1, text: 'cwd "D:\\smoke". Approval required.' });
    injection = ctx.plugin(plugin, { prompt: 'host smoke initial' });
    await new Promise(setImmediate);
    assert.equal(state.snapshot().evaluation, null);
    let assembly = await ctx.systemPrompt.assemble({ sessionId: 'smoke-a' });
    assert.equal(assembly.sections.find(s => s.name === 'prompt-lab:custom').text, 'host smoke initial');
    assert.equal(state.snapshot().status.observerRegistered, true);
    state.updateProfile({ action: 'save', id: 'default', prompt: 'host smoke saved', rules: '' });
    assert.equal(state.snapshot().assembly.stale, true);
    state.updateSettings({ contextFilter: 'redact' });
    assembly = await ctx.systemPrompt.assemble({ sessionId: 'smoke-b' });
    assert.equal(assembly.sections.find(s => s.name === 'prompt-lab:custom').text, 'host smoke saved');
    assert.equal(assembly.contexts[0].text.includes('D:\\smoke'), false);
    assert.equal(assembly.contexts[0].text.includes('Approval required.'), true);
    assert.equal(state.snapshot().assembly.stale, false);
    assert.equal(state.snapshot().assembly.scope, 'process');
    const ruleId=state.updateRule({action:'rule.create',name:'shared smoke',text:'shared policy'}).editedRuleId;
    const p=state.snapshot().profiles.find(p=>p.id==='default');
    state.updateProfile({action:'save',...p,rules:'legacy policy',ruleIds:[ruleId],expectedVersion:p.version});
    assembly=await ctx.systemPrompt.assemble();
    assert.equal(assembly.sections.find(s=>s.name==='prompt-lab:custom').text,'host smoke saved');
    assert.equal(assembly.sections.find(s=>s.name==='prompt-lab:rules').text,'## 当前规则集\nlegacy policy\n\n## shared smoke\nshared policy');
    const snapshot=state.snapshot();
    state.updateProfile({action:'save',...snapshot.profiles.find(p=>p.id==='default'),promptEnabled:false});
    assembly=await ctx.systemPrompt.assemble();
    assert.equal(assembly.sections.find(s=>s.name==='prompt-lab:custom').text,'');
    assert.ok(assembly.sections.find(s=>s.name==='prompt-lab:rules').text.includes('shared policy'));
    web=ctx.plugin(WebServer,{host:'127.0.0.1',port:0});
    await new Promise(setImmediate);
    api=ctx.plugin(ui);await new Promise(setImmediate);
    const origin=`http://127.0.0.1:${ctx.webServer.port}`;
    const headers={'x-prompt-lab-ui':'1','content-type':'application/json'};
    const live=await fetch(origin+'/prompt-lab/api',{headers}); assert.equal(live.status,200);
    assert.equal((await live.json()).version,pluginVersion);
    const studio=await fetch(origin+'/prompt-lab/api/studio',{headers});assert.equal(studio.status,200);assert.equal((await studio.json()).available,false);
    const exported=await fetch(origin+'/prompt-lab/api/export?kind=profile&id=default',{headers});
    const bundle=(await exported.json()).bundle;assert.equal(bundle.ruleSets.length,1);
    const preview=await fetch(origin+'/prompt-lab/api/import',{method:'POST',headers,body:JSON.stringify({action:'preview',bundle})});
    const plan=(await preview.json()).preview;
    const imported=await fetch(origin+'/prompt-lab/api/import',{method:'POST',headers,body:JSON.stringify({action:'commit',bundle,expectedStoreVersion:plan.storeVersion})});
    assert.equal(imported.status,200);assert.equal(state.snapshot().profiles.length,4);
    assert.equal(state.snapshot().selected,'default');
    assert.equal(fs.existsSync(path.join(temporary,'AGENTS.md')),false);
    assert.equal(fs.existsSync(path.join(temporary,'CLAUDE.md')),false);
    await api.dispose();api=null;
    assert.equal((await fetch(origin+'/prompt-lab/api',{headers})).status,404);
    assert.equal((await fetch(origin+'/prompt-lab/api/studio',{headers})).status,404);
    await web.dispose();web=null;
    await injection.dispose(); injection = null;
    assert.equal(state.snapshot().status.observerRegistered, false);
    assembly = await ctx.systemPrompt.assemble();
    assert.equal(assembly.sections.some(s => s.name === 'prompt-lab:custom'), false);
    assert.equal(assembly.sections.some(s => s.name === 'prompt-lab:rules'), false);
    assert.equal(assembly.contexts[0].text.includes('D:\\smoke'), true);
    injection = ctx.plugin(plugin, { enabled: false });
    await new Promise(setImmediate);
    state.updateSettings({ contextFilter: 'strip' });
    assembly = await ctx.systemPrompt.assemble();
    assert.equal(assembly.sections.some(s => s.name === 'prompt-lab:custom'), false);
    assert.deepEqual(assembly.contexts, []);
    assert.equal(state.snapshot().status.observerRegistered, true);
    await injection.dispose(); injection = null;
    assert.equal((await ctx.systemPrompt.assemble()).contexts.length, 1);
    console.log(JSON.stringify({ ok: true, hostVersion: version, node: process.version,
      checks: ['dynamic two-section injection', 'saved profile', 'redact', 'process snapshot', 'shared rules and independent switches', 'real WebServer API/export/import/disposal', 'studio offline isolation and disposal', 'disabled injection with strip', 'dispose restores host'] }));
  } finally {
    await injection?.dispose();
    await api?.dispose();
    await web?.dispose();
    await service?.dispose();
    if (previousHome === undefined) delete process.env.DSH_HOME; else process.env.DSH_HOME = previousHome;
    assert.equal(path.dirname(path.resolve(temporary)), path.resolve(os.tmpdir()));
    assert.ok(path.basename(temporary).startsWith('prompt-lab-host-smoke-'));
    fs.rmSync(temporary, { recursive: true, force: true });
  }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
